export function multiplierFor(risk, picks, hits) {
  const label = PAYOUTS[risk]?.[picks]?.[hits] ?? "0.00x";
  return Number(label.replaceAll(",", "").replace("x", ""));
}

export function drawNumbers(random = Math.random, count = 10) {
  const pool = Array.from({ length: 40 }, (_, index) => index + 1);
  for (let index = pool.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    [pool[index], pool[swap]] = [pool[swap], pool[index]];
  }
  return pool.slice(0, Math.max(0, Math.min(10, count)));
}

export function autoPick(random = Math.random) {
  const count = 3 + Math.floor(random() * 3);
  return drawNumbers(random, count).sort((a, b) => a - b);
}
